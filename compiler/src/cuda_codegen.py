"""CUDA code generator for NeuroCUDA IR.

Turns an (optimized) IRProgram into one self-contained `.cu` file:
  - only the kernels actually used by the program are emitted
  - host code allocates device buffers and launches kernels in IR order
  - every kernel launch is timed with CUDA events; two env vars,
    NEUROCUDA_WARMUP and NEUROCUDA_REPEAT, control untimed warm-up
    iterations and measured repeats, after which mean/min/max kernel
    time is printed -- so a single compiled binary can report a
    steady-state timing, not a cold first-launch one
  - every `random(...)` input and every `print`ed output is dumped to a
    small binary tensor file (runtime/tensor_io.hpp's format) so
    benchmarks/tensor_io.py can load the *exact* same arrays into NumPy
    or PyTorch for a fair correctness/performance comparison
  - `print` also writes a bounded, human-readable preview to stdout
    (shape, mean, a small top-left corner) since dumping a full
    1024x1024 matrix to the console is not useful

This module only ever reads IRInstr/IRProgram (src/ir.py); it never
looks at the AST, keeping CUDA generation fully decoupled from syntax.
"""

from dataclasses import dataclass

from src.errors import CodegenError


def _cpp_string_literal(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
from src.ir import IRProgram
from src.semantic import Shape

ELEMENTWISE_BINARY_OPS = {"add", "add_relu"}
ELEMENTWISE_UNARY_OPS = {"relu"}
MATMUL_OPS = {"matmul", "matmul_relu"}
KERNEL_OPS = ELEMENTWISE_BINARY_OPS | ELEMENTWISE_UNARY_OPS | MATMUL_OPS

HEADER_TEMPLATE = """\
// Auto-generated by NeuroCUDA. Do not edit by hand.
// Source program: {source_name}
#include <cstdio>
#include <cstdlib>
#include <chrono>
#include <random>
#include <cuda_runtime.h>
#include "common.cuh"
#include "tensor_io.hpp"
"""

KERNEL_SOURCES = {
    "add": """
__global__ void k_add(const float* A, const float* B, float* C, int rows, int cols) {
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    if (row < rows && col < cols) {
        int idx = row * cols + col;
        C[idx] = A[idx] + B[idx];
    }
}
""",
    "relu": """
__global__ void k_relu(const float* X, float* Y, int rows, int cols) {
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    if (row < rows && col < cols) {
        int idx = row * cols + col;
        float v = X[idx];
        Y[idx] = v > 0.0f ? v : 0.0f;
    }
}
""",
    "add_relu": """
__global__ void k_add_relu(const float* A, const float* B, float* C, int rows, int cols) {
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    if (row < rows && col < cols) {
        int idx = row * cols + col;
        float v = A[idx] + B[idx];
        C[idx] = v > 0.0f ? v : 0.0f;
    }
}
""",
    "matmul": """
__global__ void k_matmul(const float* A, const float* B, float* C, int M, int K, int N) {
    __shared__ float As[NC_TILE][NC_TILE];
    __shared__ float Bs[NC_TILE][NC_TILE];

    int row = blockIdx.y * NC_TILE + threadIdx.y;
    int col = blockIdx.x * NC_TILE + threadIdx.x;

    float acc = 0.0f;
    int num_tiles = (K + NC_TILE - 1) / NC_TILE;
    for (int t = 0; t < num_tiles; ++t) {
        int a_col = t * NC_TILE + threadIdx.x;
        int b_row = t * NC_TILE + threadIdx.y;
        As[threadIdx.y][threadIdx.x] = (row < M && a_col < K) ? A[row * K + a_col] : 0.0f;
        Bs[threadIdx.y][threadIdx.x] = (b_row < K && col < N) ? B[b_row * N + col] : 0.0f;
        __syncthreads();
        #pragma unroll
        for (int k = 0; k < NC_TILE; ++k) {
            acc += As[threadIdx.y][k] * Bs[k][threadIdx.x];
        }
        __syncthreads();
    }

    if (row < M && col < N) {
        C[row * N + col] = acc;
    }
}
""",
    "matmul_relu": """
__global__ void k_matmul_relu(const float* A, const float* B, float* C, int M, int K, int N) {
    __shared__ float As[NC_TILE][NC_TILE];
    __shared__ float Bs[NC_TILE][NC_TILE];

    int row = blockIdx.y * NC_TILE + threadIdx.y;
    int col = blockIdx.x * NC_TILE + threadIdx.x;

    float acc = 0.0f;
    int num_tiles = (K + NC_TILE - 1) / NC_TILE;
    for (int t = 0; t < num_tiles; ++t) {
        int a_col = t * NC_TILE + threadIdx.x;
        int b_row = t * NC_TILE + threadIdx.y;
        As[threadIdx.y][threadIdx.x] = (row < M && a_col < K) ? A[row * K + a_col] : 0.0f;
        Bs[threadIdx.y][threadIdx.x] = (b_row < K && col < N) ? B[b_row * N + col] : 0.0f;
        __syncthreads();
        #pragma unroll
        for (int k = 0; k < NC_TILE; ++k) {
            acc += As[threadIdx.y][k] * Bs[k][threadIdx.x];
        }
        __syncthreads();
    }

    if (row < M && col < N) {
        float v = acc;
        C[row * N + col] = v > 0.0f ? v : 0.0f;
    }
}
""",
}


@dataclass
class CodegenResult:
    source: str
    kernels_used: list  # list[str], for the CLI/explain output


class _CudaGenerator:
    def __init__(self, ir: IRProgram, source_name: str):
        self.ir = ir
        self.source_name = source_name
        self.shapes: dict[str, Shape] = {}
        self.lines: list[str] = []
        self._indent = 1

    def emit(self, line: str = "") -> None:
        if line:
            self.lines.append(("    " * self._indent) + line)
        else:
            self.lines.append("")

    def generate(self) -> CodegenResult:
        ops_used = sorted({instr.op for instr in self.ir.instructions if instr.op in KERNEL_OPS})

        parts = [HEADER_TEMPLATE.format(source_name=self.source_name)]
        for op in ops_used:
            parts.append(KERNEL_SOURCES[op])

        parts.append(self._generate_main())
        return CodegenResult(source="\n".join(parts), kernels_used=ops_used)

    def _generate_main(self) -> str:
        self.emit_preamble()
        device_ptrs: list[str] = []

        for idx, instr in enumerate(self.ir.instructions):
            if instr.op == "random":
                device_ptrs.append(self._emit_random(instr, idx))
            elif instr.op == "zeros":
                device_ptrs.append(self._emit_zeros(instr))
            elif instr.op == "load":
                device_ptrs.append(self._emit_load(instr))
            elif instr.op in ELEMENTWISE_BINARY_OPS:
                device_ptrs.append(self._emit_elementwise_binary(instr))
            elif instr.op in ELEMENTWISE_UNARY_OPS:
                device_ptrs.append(self._emit_elementwise_unary(instr))
            elif instr.op in MATMUL_OPS:
                device_ptrs.append(self._emit_matmul(instr))
            elif instr.op == "print":
                self._emit_print(instr)
            else:  # pragma: no cover - optimizer/semantic analysis restrict ops to the above
                raise CodegenError(f"codegen has no rule for IR op '{instr.op}'", instr.line)
            self.emit()

        self.emit("auto _t_end = std::chrono::steady_clock::now();")
        self.emit(
            'std::printf("TIMING total_wall_ms=%f\\n", '
            "std::chrono::duration<double, std::milli>(_t_end - _t_start).count());"
        )
        self.emit()
        for ptr in device_ptrs:
            self.emit(f"CUDA_CHECK(cudaFree({ptr}));")
        self.emit("return 0;")
        self._indent -= 1
        self.lines.append("}")
        return "\n".join(self.lines)

    def emit_preamble(self) -> None:
        self.lines.append("int main() {")
        self.emit("const char* seed_env = std::getenv(\"NEUROCUDA_SEED\");")
        self.emit("unsigned int seed = seed_env ? (unsigned int)std::atoi(seed_env) : 42u;")
        self.emit("const char* repeat_env = std::getenv(\"NEUROCUDA_REPEAT\");")
        self.emit("int repeat = repeat_env ? std::atoi(repeat_env) : 1;")
        self.emit("if (repeat < 1) repeat = 1;")
        self.emit("const char* warmup_env = std::getenv(\"NEUROCUDA_WARMUP\");")
        self.emit("int warmup = warmup_env ? std::atoi(warmup_env) : 0;")
        self.emit("if (warmup < 0) warmup = 0;")
        self.emit("auto _t_start = std::chrono::steady_clock::now();")
        self.emit()

    # -- per-op emitters -------------------------------------------------------

    def _emit_random(self, instr, idx: int) -> str:
        name = instr.result
        rows, cols = instr.dims
        self.shapes[name] = instr.shape
        n = rows * cols
        self.emit(f"// {name} = random({rows}, {cols})")
        self.emit(f"float* h_{name} = (float*)std::malloc(sizeof(float) * {n});")
        self.emit("{")
        self._indent += 1
        self.emit(f"std::mt19937 rng(seed + {idx * 7919}u);")
        self.emit("std::uniform_real_distribution<float> dist(0.0f, 1.0f);")
        self.emit(f"for (int i = 0; i < {n}; ++i) h_{name}[i] = dist(rng);")
        self._indent -= 1
        self.emit("}")
        self.emit(f'nc_write_tensor_file("{name}.nct", h_{name}, {rows}, {cols});')
        ptr = f"d_{name}"
        self.emit(f"float* {ptr};")
        self.emit(f"CUDA_CHECK(cudaMalloc(&{ptr}, sizeof(float) * {n}));")
        self.emit(
            f"CUDA_CHECK(cudaMemcpy({ptr}, h_{name}, sizeof(float) * {n}, cudaMemcpyHostToDevice));"
        )
        self.emit(f"std::free(h_{name});")
        return ptr

    def _emit_zeros(self, instr) -> str:
        name = instr.result
        rows, cols = instr.dims
        self.shapes[name] = instr.shape
        n = rows * cols
        self.emit(f"// {name} = zeros({rows}, {cols})")
        ptr = f"d_{name}"
        self.emit(f"float* {ptr};")
        self.emit(f"CUDA_CHECK(cudaMalloc(&{ptr}, sizeof(float) * {n}));")
        self.emit(f"CUDA_CHECK(cudaMemset({ptr}, 0, sizeof(float) * {n}));")
        return ptr

    def _emit_load(self, instr) -> str:
        name = instr.result
        rows, cols = instr.shape.rows, instr.shape.cols
        self.shapes[name] = instr.shape
        n = rows * cols
        literal = _cpp_string_literal(instr.path)
        self.emit(f"// {name} = load({literal})")
        self.emit(f"float* h_{name} = nc_read_tensor_file({literal}, {rows}, {cols});")
        ptr = f"d_{name}"
        self.emit(f"float* {ptr};")
        self.emit(f"CUDA_CHECK(cudaMalloc(&{ptr}, sizeof(float) * {n}));")
        self.emit(
            f"CUDA_CHECK(cudaMemcpy({ptr}, h_{name}, sizeof(float) * {n}, cudaMemcpyHostToDevice));"
        )
        self.emit(f"std::free(h_{name});")
        return ptr

    def _emit_elementwise_binary(self, instr) -> str:
        name = instr.result
        self.shapes[name] = instr.shape
        rows, cols = instr.shape.rows, instr.shape.cols
        n = rows * cols
        a_name, b_name = instr.args
        kernel = "k_add" if instr.op == "add" else "k_add_relu"

        self.emit(f"// {name} = {instr.op}({a_name}, {b_name})")
        ptr = f"d_{name}"
        self.emit(f"float* {ptr};")
        self.emit(f"CUDA_CHECK(cudaMalloc(&{ptr}, sizeof(float) * {n}));")
        self.emit("{")
        self._indent += 1
        self.emit(f"dim3 block(NC_ELEMENTWISE_BLOCK, NC_ELEMENTWISE_BLOCK);")
        self.emit(
            f"dim3 grid(({cols} + block.x - 1) / block.x, ({rows} + block.y - 1) / block.y);"
        )
        self._emit_timed_launch(
            kernel_call=f"{kernel}<<<grid, block>>>(d_{a_name}, d_{b_name}, {ptr}, {rows}, {cols});",
            timing_label=name,
        )
        self._indent -= 1
        self.emit("}")
        return ptr

    def _emit_elementwise_unary(self, instr) -> str:
        name = instr.result
        self.shapes[name] = instr.shape
        rows, cols = instr.shape.rows, instr.shape.cols
        n = rows * cols
        (x_name,) = instr.args

        self.emit(f"// {name} = relu({x_name})")
        ptr = f"d_{name}"
        self.emit(f"float* {ptr};")
        self.emit(f"CUDA_CHECK(cudaMalloc(&{ptr}, sizeof(float) * {n}));")
        self.emit("{")
        self._indent += 1
        self.emit("dim3 block(NC_ELEMENTWISE_BLOCK, NC_ELEMENTWISE_BLOCK);")
        self.emit(
            f"dim3 grid(({cols} + block.x - 1) / block.x, ({rows} + block.y - 1) / block.y);"
        )
        self._emit_timed_launch(
            kernel_call=f"k_relu<<<grid, block>>>(d_{x_name}, {ptr}, {rows}, {cols});",
            timing_label=name,
        )
        self._indent -= 1
        self.emit("}")
        return ptr

    def _emit_matmul(self, instr) -> str:
        name = instr.result
        self.shapes[name] = instr.shape
        a_name, b_name = instr.args
        a_shape = self.shapes[a_name]
        b_shape = self.shapes[b_name]
        m, k, n_dim = a_shape.rows, a_shape.cols, b_shape.cols
        n = m * n_dim
        kernel = "k_matmul" if instr.op == "matmul" else "k_matmul_relu"

        self.emit(f"// {name} = {instr.op}({a_name}, {b_name})")
        ptr = f"d_{name}"
        self.emit(f"float* {ptr};")
        self.emit(f"CUDA_CHECK(cudaMalloc(&{ptr}, sizeof(float) * {n}));")
        self.emit("{")
        self._indent += 1
        self.emit("dim3 block(NC_TILE, NC_TILE);")
        self.emit(f"dim3 grid(({n_dim} + NC_TILE - 1) / NC_TILE, ({m} + NC_TILE - 1) / NC_TILE);")
        self._emit_timed_launch(
            kernel_call=(
                f"{kernel}<<<grid, block>>>(d_{a_name}, d_{b_name}, {ptr}, {m}, {k}, {n_dim});"
            ),
            timing_label=name,
        )
        self._indent -= 1
        self.emit("}")
        return ptr

    def _emit_timed_launch(self, *, kernel_call: str, timing_label: str) -> None:
        self.emit("cudaEvent_t ev_start, ev_stop;")
        self.emit("CUDA_CHECK(cudaEventCreate(&ev_start));")
        self.emit("CUDA_CHECK(cudaEventCreate(&ev_stop));")
        self.emit("for (int _warm = 0; _warm < warmup; ++_warm) {")
        self._indent += 1
        self.emit(kernel_call)
        self.emit("CUDA_CHECK(cudaGetLastError());")
        self._indent -= 1
        self.emit("}")
        self.emit("if (warmup > 0) { CUDA_CHECK(cudaDeviceSynchronize()); }")
        self.emit("float ms_sum = 0.0f, ms_min = 1e30f, ms_max = 0.0f;")
        self.emit("for (int _rep = 0; _rep < repeat; ++_rep) {")
        self._indent += 1
        self.emit("CUDA_CHECK(cudaEventRecord(ev_start));")
        self.emit(kernel_call)
        self.emit("CUDA_CHECK(cudaGetLastError());")
        self.emit("CUDA_CHECK(cudaEventRecord(ev_stop));")
        self.emit("CUDA_CHECK(cudaEventSynchronize(ev_stop));")
        self.emit("float ms = 0.0f;")
        self.emit("CUDA_CHECK(cudaEventElapsedTime(&ms, ev_start, ev_stop));")
        self.emit("ms_sum += ms;")
        self.emit("if (ms < ms_min) ms_min = ms;")
        self.emit("if (ms > ms_max) ms_max = ms;")
        self._indent -= 1
        self.emit("}")
        self.emit(f'std::printf("TIMING {timing_label}_mean_ms=%f\\n", ms_sum / repeat);')
        self.emit(f'std::printf("TIMING {timing_label}_min_ms=%f\\n", ms_min);')
        self.emit(f'std::printf("TIMING {timing_label}_max_ms=%f\\n", ms_max);')
        self.emit("CUDA_CHECK(cudaEventDestroy(ev_start));")
        self.emit("CUDA_CHECK(cudaEventDestroy(ev_stop));")

    def _emit_print(self, instr) -> None:
        name = instr.args[0]
        shape = self.shapes[name]
        rows, cols = shape.rows, shape.cols
        n = rows * cols
        preview_rows = min(rows, 4)
        preview_cols = min(cols, 4)

        self.emit(f"// print {name}")
        self.emit("{")
        self._indent += 1
        self.emit(f"float* h_{name} = (float*)std::malloc(sizeof(float) * {n});")
        self.emit(
            f"CUDA_CHECK(cudaMemcpy(h_{name}, d_{name}, sizeof(float) * {n}, "
            "cudaMemcpyDeviceToHost));"
        )
        self.emit(f'nc_write_tensor_file("{name}.nct", h_{name}, {rows}, {cols});')
        self.emit("double sum = 0.0;")
        self.emit(f"for (int i = 0; i < {n}; ++i) sum += h_{name}[i];")
        self.emit(f"double mean = sum / {n}.0;")
        self.emit(f'std::printf("== {name} : shape ({rows}, {cols}) ==\\n");')
        self.emit('std::printf("mean=%f\\n", mean);')
        self.emit(f'std::printf("preview (top-left {preview_rows}x{preview_cols}):\\n");')
        self.emit(f"for (int r = 0; r < {preview_rows}; ++r) {{")
        self._indent += 1
        self.emit(f"for (int c = 0; c < {preview_cols}; ++c) {{")
        self._indent += 1
        self.emit(f'std::printf("%8.4f ", h_{name}[r * {cols} + c]);')
        self._indent -= 1
        self.emit("}")
        self.emit('std::printf("\\n");')
        self._indent -= 1
        self.emit("}")
        self.emit(f"std::free(h_{name});")
        self._indent -= 1
        self.emit("}")


def generate_cuda(ir: IRProgram, source_name: str = "program") -> CodegenResult:
    return _CudaGenerator(ir, source_name).generate()
